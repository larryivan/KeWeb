#!/usr/bin/env node
// scripts/home-land.mjs — generates docs/.vitepress/components/home/land.generated.ts (pnpm home:land).
// Square dot grid over the Afro-Eurasia frame (geo/frame.mjs), sampled against world-atlas land-110m
// (land only: no borders, no country names). Emits ONE relative-move path: `M{x} {y}h0` at a row start,
// then `m{dx} 0h0` per dot. Fails (exit 1) if Taiwan or Hainan get fewer than 2 dots.
// Manual tool: never part of docs:build.
import { createRequire } from 'node:module'
import { readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { gzipSync } from 'node:zlib'
import * as d3 from 'd3-geo'
import { feature } from 'topojson-client'
import { FRAME, MAP_W, STEP, computeH, makeProjection } from '../docs/.vitepress/components/home/geo/frame.mjs'

const require = createRequire(import.meta.url)
const topo = JSON.parse(readFileSync(require.resolve('world-atlas/land-110m.json'), 'utf8'))
const land = feature(topo, topo.objects.land)

const H = computeH(d3)
const p = makeProjection(d3, H)

const BOXES = { Taiwan: [119.9, 21.8, 122.1, 25.4], Hainan: [108.5, 18.1, 111.1, 20.2] }
const counts = { Taiwan: 0, Hainan: 0 }
let d = ''
let dots = 0
for (let y = STEP / 2; y < H; y += STEP) {
  let lastX = null
  for (let x = STEP / 2; x < MAP_W; x += STEP) {
    const ll = p.invert([x, y])
    if (!ll || !d3.geoContains(land, ll)) continue
    const back = p(ll)
    if (!back || Math.abs(back[0] - x) > 0.5 || Math.abs(back[1] - y) > 0.5) continue // outside the valid region
    for (const [k, [x0, y0, x1, y1]] of Object.entries(BOXES)) {
      if (ll[0] >= x0 && ll[0] <= x1 && ll[1] >= y0 && ll[1] <= y1) counts[k]++
    }
    d += lastX === null ? `M${x.toFixed(1)} ${y.toFixed(1)}h0` : `m${(x - lastX).toFixed(0)} 0h0`
    lastX = x
    dots++
  }
}

const gz = gzipSync(Buffer.from(d), { level: 9 }).length
console.log(`home-land: w ${MAP_W}, h ${H}, step ${STEP}, ${dots} dots, path ${(d.length / 1000).toFixed(1)} KB raw, ${(gz / 1000).toFixed(2)} KB gzip`)
console.log(`home-land: Taiwan ${counts.Taiwan} dots, Hainan ${counts.Hainan} dots`)
let ok = true
for (const [k, n] of Object.entries(counts)) {
  if (n < 2) { console.error(`home-land: FAIL — ${k} has ${n} dots (need >= 2)`); ok = false }
}
if (!ok) process.exit(1)

const out = fileURLToPath(new URL('../docs/.vitepress/components/home/land.generated.ts', import.meta.url))
const src =
  `// GENERATED by scripts/home-land.mjs (pnpm home:land) — do not edit by hand.\n` +
  `// world-atlas 2.0.2 land-110m, Natural Earth rotate(-65), frame lon [${FRAME.lon.join(", ")}] lat [${FRAME.lat.join(", ")}].\n` +
  `// Taiwan ${counts.Taiwan} dots, Hainan ${counts.Hainan} dots. Path ${gz} bytes gzip.\n` +
  `export const LAND = { w: ${MAP_W}, h: ${H}, step: ${STEP}, dots: ${dots}, d: ${JSON.stringify(d)} } as const\n`
writeFileSync(out, src)
console.log(`home-land: wrote ${out}`)
